const APP_ORIGIN = (process.env.APP_ORIGIN || 'https://detailprocrm.ru').replace(/\/$/, '');

// Escape для подстановки пользовательских строк (имя владельца, название
// студии) в HTML-тексты. Без этого имя вида «Иванов&Co» сломает parseMode='HTML'
// — Telegram вернёт 400. Маленький локальный helper, чтобы модуль не зависел
// от server/lib/telegram.cjs (избегаем циклов в require).
function esc(s) {
  if (s == null) return '';
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

function btnTariffs(label = 'Выбрать тариф') {
  return [{ text: label, url: `${APP_ORIGIN}/profile` }];
}

function btnReferral(referralCode, label = 'Расскажи друзьям') {
  // Раздаём собственную реферальную ссылку юзера — он копирует и шарит.
  // Если кода нет (старая студия до миграции 005) — фолбэк на /profile,
  // там есть ReferralSection с генерацией.
  const url = referralCode ? `${APP_ORIGIN}/?ref=${referralCode}` : `${APP_ORIGIN}/profile`;
  return [{ text: label, url }];
}

function btnApp(label) {
  return [{ text: label, url: `${APP_ORIGIN}/` }];
}

