'use strict';
/**
 * Лёгкий шаблонизатор для гендерных форм в русских текстах.
 *
 * Синтаксис:
 *   {а}        — окончание для женского рода. По умолчанию (мужской) — пусто.
 *                  «забыл{а}»          → м: «забыл»,    ж: «забыла»
 *   {м/ж}      — две явные формы через слэш.
 *                  «был{/а}»           → м: «был»,      ж: «была»
 *                  «гото{в/ва}»        → м: «готов»,    ж: «готова»
 *
 * Если gender === null/undefined — выбираем мужскую форму (default).
 *
 * Edge cases:
 *   - Открытая фигурная скобка без закрытия не трогается (на всякий случай).
 *   - Слэш ВНУТРИ {…} — разделитель форм. Если слэша нет — это «{а}»-стиль.
 */
function applyGender(text, gender) {
  if (text == null) return '';
  const isFemale = gender === 'f';

  // Сначала обрабатываем формы вида {м/ж} — они более специфичные.
  let out = String(text).replace(/\{([^{}/]*)\/([^{}]*)\}/g, (_, m, f) => {
    return isFemale ? f : m;
  });

  // Затем простые {а} — окончание-добавка для ж.р.
  out = out.replace(/\{([^{}]*)\}/g, (_, suffix) => {
    return isFemale ? suffix : '';
  });

  return out;
}

module.exports = { applyGender };
