-- 011_daily_summary_time.sql
--
-- Время утренней сводки в Telegram-боте — настраиваемое per-studio.
--
-- ДО этой миграции время было захардкожено в reminders.cjs (9:00 локального
-- времени студии). Юзеры жаловались: «бот не спросил, во сколько присылать»
-- и «у нас в студии работа начинается в 8:00, сводка в 9:00 опаздывает».
--
-- Решение: одно время на студию (а не per-user, чтобы не плодить настройки
-- и UI). Меняет только владелец — в боте при онбординге, командой /время,
-- или в Профиле СРМ → секция «Студия».
--
-- Поля:
--   • daily_summary_time      — TIME (без TZ). Интерпретируется в часовом
--                               поясе студии (studios.timezone). NULL = «не
--                               присылать сводку этой студии вообще».
--   • daily_summary_time_set  — флаг «owner уже выбрал явно». FALSE для
--                               существующих студий → бот при следующем
--                               взаимодействии переспросит у owner-а.
--
-- DEFAULT '09:00:00': если бот переспросить не успеет (например, owner
-- редко открывает бота), сводка продолжит приходить в 9:00 — это и так
-- работало раньше, никакого регресса.
--
-- Идемпотентно — IF NOT EXISTS.

ALTER TABLE saas_meta.studios
  ADD COLUMN IF NOT EXISTS daily_summary_time     TIME    DEFAULT '09:00:00',
  ADD COLUMN IF NOT EXISTS daily_summary_time_set BOOLEAN NOT NULL DEFAULT FALSE;
